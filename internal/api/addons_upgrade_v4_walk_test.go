// Add-to-catalog (walk 1 L11): the API and so the CLI refuse a version that
// was never released, on the preview too.
func TestAddToCatalogRoute_VersionThatDoesNotExist_Is400(t *testing.T) {
	for _, dryRun := range []bool{false, true} {
		srv, git := newUpgradeWalkServer(t)
		w := postUpgrade(t, srv, "/api/v1/catalog/addons", "admin", map[string]interface{}{
			"dry_run": dryRun,
			"addons": []map[string]interface{}{{
				"name": "metrics-server", "repo_url": "https://kubernetes-sigs.github.io/metrics-server",
				"chart": "metrics-server", "version": "9.9.9", "namespace": "kube-system",
			}},
		})
		if w.Code != http.StatusBadRequest {
			t.Fatalf("dry_run=%v: status = %d, want 400 (body=%s)", dryRun, w.Code, w.Body.String())
		}
		msg, code, _ := decodeErrorBody(t, w)
		if code != CodeVersionNotFound {
			t.Errorf("code = %q, want %q", code, CodeVersionNotFound)
		}
		want := "Version 9.9.9 of metrics-server was not found in its chart repository (https://kubernetes-sigs.github.io/metrics-server). Nothing was changed. Pick a version that the repository lists."
		if msg != want {
			t.Errorf("message =\n  %q\nwant\n  %q", msg, want)
		}
		if strings.Contains(msg, "network or registry error") {
			t.Error("a missing version must not be blamed on the network")
		}
		if len(git.prs) != 0 {
			t.Error("no pull request may be opened")
		}
	}
}

func TestWriteUpgradeError_Codes(t *testing.T) {
	for _, tc := range []struct {
		name       string
		err        error
		wantStatus int
		wantCode   string
	}{
		{"version not found", fmt.Errorf("x: %w", orchestrator.ErrChartVersionNotFound), http.StatusBadRequest, CodeVersionNotFound},
		{"chart repo unreadable", fmt.Errorf("x: %w", orchestrator.ErrChartVersionLookupFailed), http.StatusBadGateway, CodeChartRepoUnreadable},
		{"nothing to change", fmt.Errorf("x: %w", orchestrator.ErrUpgradeNothingToDo), http.StatusBadRequest, CodeNothingToChange},
		{"request invalid", fmt.Errorf("x: %w", orchestrator.ErrUpgradeRequestInvalid), http.StatusBadRequest, CodeInvalidRequest},
		{"not in catalog", fmt.Errorf("x: %w", orchestrator.ErrV4AddonNotInCatalog), http.StatusNotFound, CodeNotInCatalog},
		{"half converted repo", fmt.Errorf("x: %w", orchestrator.ErrMixedRepoLayout), http.StatusConflict, CodeRepoLayout},
		{"git host broke", errors.New("the git host returned 500"), http.StatusBadGateway, ""},
	} {
		t.Run(tc.name, func(t *testing.T) {
			rw := httptest.NewRecorder()
			writeUpgradeError(rw, tc.err)
			if rw.Code != tc.wantStatus {
				t.Fatalf("status = %d, want %d", rw.Code, tc.wantStatus)
			}
			if _, code, _ := decodeErrorBody(t, rw); code != tc.wantCode {
				t.Errorf("code = %q, want %q", code, tc.wantCode)
			}
		})
	}
}
