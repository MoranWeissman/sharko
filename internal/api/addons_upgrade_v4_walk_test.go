// upgradeFakeGit is a Git host that keeps what is written to it, so a test
// can read back what an upgrade pull request really changed.
type upgradeFakeGit struct {
	mu    sync.Mutex
	files map[string][]byte
	prs   []string
}

func (f *upgradeFakeGit) GetFileContent(_ context.Context, path, _ string) ([]byte, error) {
	f.mu.Lock()
	defer f.mu.Unlock()
	data, ok := f.files[path]
	if !ok {
		return nil, fmt.Errorf("path %q not found: %w", path, gitprovider.ErrFileNotFound)
	}
	return data, nil
}

func (f *upgradeFakeGit) ListDirectory(_ context.Context, dir, _ string) ([]string, error) {
	f.mu.Lock()
	defer f.mu.Unlock()
	prefix := strings.TrimSuffix(dir, "/") + "/"
	var out []string
	for p := range f.files {
		if rest := strings.TrimPrefix(p, prefix); rest != p && !strings.Contains(rest, "/") {
			out = append(out, rest)
		}
	}
	if len(out) == 0 {
		return nil, fmt.Errorf("directory %q not found: %w", dir, gitprovider.ErrFileNotFound)
	}
	sort.Strings(out)
	return out, nil
}

func (f *upgradeFakeGit) ListPullRequests(context.Context, string) ([]gitprovider.PullRequest, error) {
	return nil, nil
}
func (f *upgradeFakeGit) TestConnection(context.Context) error               { return nil }
func (f *upgradeFakeGit) CreateBranch(context.Context, string, string) error { return nil }
func (f *upgradeFakeGit) CreateOrUpdateFile(_ context.Context, path string, content []byte, _, _ string) error {
	f.mu.Lock()
	defer f.mu.Unlock()
	f.files[path] = content
	return nil
}
func (f *upgradeFakeGit) BatchCreateFiles(_ context.Context, files map[string][]byte, _, _ string) error {
	f.mu.Lock()
	defer f.mu.Unlock()
	for p, c := range files {
		f.files[p] = c
	}
	return nil
}
func (f *upgradeFakeGit) DeleteFile(context.Context, string, string, string) error { return nil }
func (f *upgradeFakeGit) CreatePullRequest(_ context.Context, title, _, head, _ string) (*gitprovider.PullRequest, error) {
	f.mu.Lock()
	defer f.mu.Unlock()
	f.prs = append(f.prs, title)
	return &gitprovider.PullRequest{ID: len(f.prs), Title: title, SourceBranch: head, URL: fmt.Sprintf("https://git.example/pr/%d", len(f.prs))}, nil
}
func (f *upgradeFakeGit) MergePullRequest(context.Context, int) error { return nil }
func (f *upgradeFakeGit) GetPullRequestStatus(context.Context, int) (string, error) {
	return "open", nil
}
func (f *upgradeFakeGit) DeleteBranch(context.Context, string) error { return nil }

const walkPodinfoRepo = "https://stefanprodan.github.io/podinfo"

// newUpgradeWalkServer builds a v4 repo with podinfo 6.7.1 in the catalog,
// switched on on spoke-1 (following the catalog) and spoke-2 (own pin). The
// chart repository in these tests publishes 6.7.1, 6.8.0 and 6.9.0.
func newUpgradeWalkServer(t *testing.T) (*Server, *upgradeFakeGit) {
	t.Helper()
	catalogBody, err := config.SaveAddonCatalog(config.AddonCatalogSpec{
		Addons: map[string]config.AddonCatalogEntry{
			"podinfo": {RepoURL: walkPodinfoRepo, Chart: "podinfo", Version: "6.7.1", Namespace: "podinfo"},
		},
	})
	if err != nil {
		t.Fatal(err)
	}
	clusterFile := func(cluster, pin string) []byte {
		body, saveErr := models.SaveClusterAddons(models.ClusterAddonsSpec{
			Cluster: cluster,
			Addons:  map[string]models.ClusterAddonsAddon{"podinfo": {Enabled: true, Version: pin}},
		})
		if saveErr != nil {
			t.Fatal(saveErr)
		}
		return body
	}
	git := &upgradeFakeGit{files: map[string][]byte{
		orchestrator.EnginePinPath:             []byte("apiVersion: argoproj.io/v1alpha1\nkind: Application\n"),
		orchestrator.V4ManagedClustersPath:     []byte("clusters:\n  - name: spoke-1\n  - name: spoke-2\n"),
		config.AddonCatalogPath:                catalogBody,
		"cluster-addons/spoke-1.yaml":          clusterFile("spoke-1", ""),
		"cluster-addons/spoke-2.yaml":          clusterFile("spoke-2", "6.7.1"),
		"values/global/podinfo.yaml":           []byte("# Generated by Sharko from podinfo@6.7.1 on 2026-11-26\n# Chart source: " + walkPodinfoRepo + "\n# AI annotation: disabled\n# sharko: managed=true\nimage:\n  tag: 6.7.1\nreplicaCount: 1\n"),
		"values/clusters/spoke-1/podinfo.yaml": []byte("# no overrides\n"),
	}}

	srv := newIsolatedTestServer(t)
	argoStub := startArgocdStub(t, nil)
	seedActiveConnectionWithArgo(t, srv, argoStub.URL)
	srv.connSvc.SetGitProviderOverride(git)
	srv.chartVersionCheckFn = func(_ context.Context, _, _, version string) (bool, bool, error) {
		switch version {
		case "6.7.1", "6.8.0", "6.9.0":
			return true, true, nil
		}
		return false, true, nil
	}
	srv.chartDefaultsFn = func(_ context.Context, _, _, version string) ([]byte, error) {
		return []byte("image:\n  tag: " + version + "\nreplicaCount: 1\n"), nil
	}
	return srv, git
}

func postUpgrade(t *testing.T, srv *Server, path, role string, body map[string]interface{}) *httptest.ResponseRecorder {
	t.Helper()
	raw, _ := json.Marshal(body)
	req := httptest.NewRequest(http.MethodPost, path, bytes.NewReader(raw))
	req.Header.Set("Content-Type", "application/json")
	withRole(req, role)
	w := httptest.NewRecorder()
	NewRouter(srv, nil).ServeHTTP(w, req)
	return w
}

func (f *upgradeFakeGit) catalogVersion(t *testing.T, addon string) string {
	t.Helper()
	spec, err := config.LoadAddonCatalog(f.files[config.AddonCatalogPath])
	if err != nil {
		t.Fatal(err)
	}
	return spec.Addons[addon].Version
}

func (f *upgradeFakeGit) pin(t *testing.T, cluster, addon string) string {
	t.Helper()
	spec, err := models.LoadClusterAddons(f.files["cluster-addons/"+cluster+".yaml"])
	if err != nil {
		t.Fatal(err)
	}
	return spec.Addons[addon].Version
}

// The main Upgrade button: POST /addons/{name}/upgrade on a v4 repo.
func TestUpgradeAddonRoute_V4_AllClusters_OpensAPullRequestThatMovesTheAddon(t *testing.T) {
	srv, git := newUpgradeWalkServer(t)

	w := postUpgrade(t, srv, "/api/v1/addons/podinfo/upgrade", "operator", map[string]interface{}{"version": "6.8.0"})
	if w.Code == http.StatusConflict {
		t.Fatalf("the v4 refusal is back: %s", w.Body.String())
	}
	if w.Code != http.StatusOK {
		t.Fatalf("status = %d, want 200 (body=%s)", w.Code, w.Body.String())
	}
	if strings.Contains(w.Body.String(), "not supported on a v4 repo") {
		t.Fatalf("body still carries the refusal: %s", w.Body.String())
	}
	if len(git.prs) != 1 {
		t.Fatalf("expected one pull request, got %v", git.prs)
	}
	if got := git.catalogVersion(t, "podinfo"); got != "6.8.0" {
		t.Errorf("catalog version = %q, want 6.8.0", got)
	}
	if got := git.pin(t, "spoke-2", "podinfo"); got != "" {
		t.Errorf("spoke-2 still has its own pin %q — it would be called behind", got)
	}
	if !strings.Contains(string(git.files["values/global/podinfo.yaml"]), "  tag: 6.8.0\n") {
		t.Errorf("the seeded image tag did not follow the chart:\n%s", git.files["values/global/podinfo.yaml"])
	}
	if _, ok := git.files["configuration/addons-catalog.yaml"]; ok {
		t.Error("a v4 repo must never get the old catalog file")
	}
}

func TestUpgradeAddonRoute_V4_OneCluster_SetsThatClustersPin(t *testing.T) {
	srv, git := newUpgradeWalkServer(t)

	w := postUpgrade(t, srv, "/api/v1/addons/podinfo/upgrade", "operator", map[string]interface{}{"version": "6.8.0", "cluster": "spoke-1"})
	if w.Code != http.StatusOK {
		t.Fatalf("status = %d, want 200 (body=%s)", w.Code, w.Body.String())
	}
	if got := git.pin(t, "spoke-1", "podinfo"); got != "6.8.0" {
		t.Errorf("spoke-1 pin = %q, want 6.8.0", got)
	}
	if got := git.catalogVersion(t, "podinfo"); got != "6.7.1" {
		t.Errorf("a one-cluster upgrade must not move the catalog, got %q", got)
	}
	var body orchestrator.GitResult
	if err := json.Unmarshal(w.Body.Bytes(), &body); err != nil {
		t.Fatal(err)
	}
	if len(body.Warnings) != 1 || !strings.Contains(body.Warnings[0], "image.tag (6.7.1, new chart default 6.8.0)") {
		t.Errorf("the response must say the shared values file keeps the old image tag, got %q", body.Warnings)
	}
}

func TestUpgradeAddonRoute_V4_DryRun_WritesNothing(t *testing.T) {
	srv, git := newUpgradeWalkServer(t)

	w := postUpgrade(t, srv, "/api/v1/addons/podinfo/upgrade", "operator", map[string]interface{}{"version": "6.8.0", "dry_run": true})
	if w.Code != http.StatusOK {
		t.Fatalf("status = %d, want 200 (body=%s)", w.Code, w.Body.String())
	}
	var body orchestrator.GitResult
	if err := json.Unmarshal(w.Body.Bytes(), &body); err != nil {
		t.Fatal(err)
	}
	if body.DryRun == nil || len(body.DryRun.FilesToWrite) != 3 {
		t.Fatalf("expected a preview of 3 files (catalog, spoke-2, global values), got %+v", body.DryRun)
	}
	if len(git.prs) != 0 || git.catalogVersion(t, "podinfo") != "6.7.1" {
		t.Error("a dry run must not open a pull request or change a file")
	}
}

// A version that is not in the chart repository: 400, before any pull
// request, on every door, with the version named.
func TestUpgradeRoutes_V4_VersionThatDoesNotExist_Is400BeforeAnyPullRequest(t *testing.T) {
	doors := []struct {
		name string
		path string
		body func(version string) map[string]interface{}
	}{
		{"upgrade all clusters", "/api/v1/addons/podinfo/upgrade", func(v string) map[string]interface{} {
			return map[string]interface{}{"version": v}
		}},
		{"upgrade all clusters dry run", "/api/v1/addons/podinfo/upgrade", func(v string) map[string]interface{} {
			return map[string]interface{}{"version": v, "dry_run": true}
		}},
		{"upgrade one cluster", "/api/v1/addons/podinfo/upgrade", func(v string) map[string]interface{} {
			return map[string]interface{}{"version": v, "cluster": "spoke-1"}
		}},
		{"upgrade-clusters", "/api/v1/addons/podinfo/upgrade-clusters", func(v string) map[string]interface{} {
			return map[string]interface{}{"version": v, "clusters": []string{"spoke-1"}, "yes": true}
		}},
		{"upgrade-clusters dry run", "/api/v1/addons/podinfo/upgrade-clusters", func(v string) map[string]interface{} {
			return map[string]interface{}{"version": v, "clusters": []string{"spoke-1"}, "dry_run": true}
		}},
		{"upgrade-batch", "/api/v1/addons/upgrade-batch", func(v string) map[string]interface{} {
			return map[string]interface{}{"upgrades": map[string]string{"podinfo": v}}
		}},
	}
	for _, version := range []string{"99.0.0", "abc"} {
		for _, door := range doors {
			t.Run(version+"/"+door.name, func(t *testing.T) {
				srv, git := newUpgradeWalkServer(t)
				w := postUpgrade(t, srv, door.path, "operator", door.body(version))
				if w.Code != http.StatusBadRequest {
					t.Fatalf("status = %d, want 400 (body=%s)", w.Code, w.Body.String())
				}
				msg, code, _ := decodeErrorBody(t, w)
				if code != CodeVersionNotFound {
					t.Errorf("code = %q, want %q", code, CodeVersionNotFound)
				}
				want := "Version " + version + " of podinfo was not found in its chart repository (" + walkPodinfoRepo + "). Nothing was changed. Pick a version that the repository lists."
				if msg != want {
					t.Errorf("message =\n  %q\nwant\n  %q", msg, want)
				}
				if len(git.prs) != 0 {
					t.Errorf("a pull request was opened: %v", git.prs)
				}
				if git.catalogVersion(t, "podinfo") != "6.7.1" || git.pin(t, "spoke-1", "podinfo") != "" {
					t.Error("a file was changed")
				}
			})
		}
	}
}

// A chart repository that cannot be reached is a 502 that says so, and it
// does not call the version wrong.
func TestUpgradeAddonRoute_V4_ChartRepositoryUnreachable_Is502AndDoesNotBlameTheVersion(t *testing.T) {
	srv, git := newUpgradeWalkServer(t)
	srv.chartVersionCheckFn = func(context.Context, string, string, string) (bool, bool, error) {
		return false, true, errors.New("dial tcp: lookup stefanprodan.github.io: no such host")
	}

	w := postUpgrade(t, srv, "/api/v1/addons/podinfo/upgrade", "operator", map[string]interface{}{"version": "6.8.0"})
	if w.Code != http.StatusBadGateway {
		t.Fatalf("status = %d, want 502 (body=%s)", w.Code, w.Body.String())
	}
	msg, code, _ := decodeErrorBody(t, w)
	if code != CodeChartRepoUnreadable {
		t.Errorf("code = %q, want %q", code, CodeChartRepoUnreadable)
	}
	want := "Sharko could not reach the chart repository of podinfo (" + walkPodinfoRepo + "), so it could not check that version 6.8.0 exists. Nothing was changed. Try again in a moment."
	if msg != want {
		t.Errorf("message =\n  %q\nwant\n  %q", msg, want)
	}
	if strings.Contains(msg, "was not found") {
		t.Errorf("the version is blamed for a lookup that failed: %q", msg)
	}
	if len(git.prs) != 0 {
		t.Error("no pull request may be opened")
	}
}

// Mistakes a caller can fix are 4xx, never "bad gateway".
func TestUpgradeRoutes_V4_CallerMistakesAre4xx(t *testing.T) {
	for _, tc := range []struct {
		name       string
		path       string
		body       map[string]interface{}
		wantStatus int
		wantCode   string
	}{
		{"addon not in the catalog", "/api/v1/addons/nosuchaddon/upgrade", map[string]interface{}{"version": "1.0.0"}, http.StatusNotFound, CodeNotInCatalog},
		{"addon not switched on on that cluster", "/api/v1/addons/podinfo/upgrade-clusters", map[string]interface{}{"version": "6.8.0", "clusters": []string{"spoke-9"}, "yes": true}, http.StatusBadRequest, CodeInvalidRequest},
		{"same version again", "/api/v1/addons/podinfo/upgrade-clusters", map[string]interface{}{"version": "6.7.1", "clusters": []string{"spoke-1"}, "yes": true}, http.StatusBadRequest, CodeNothingToChange},
		{"no clusters", "/api/v1/addons/podinfo/upgrade-clusters", map[string]interface{}{"version": "6.8.0", "clusters": []string{}, "yes": true}, http.StatusBadRequest, CodeInvalidRequest},
	} {
		t.Run(tc.name, func(t *testing.T) {
			srv, git := newUpgradeWalkServer(t)
			w := postUpgrade(t, srv, tc.path, "operator", tc.body)
			if w.Code != tc.wantStatus {
				t.Fatalf("status = %d, want %d (body=%s)", w.Code, tc.wantStatus, w.Body.String())
			}
			if _, code, _ := decodeErrorBody(t, w); code != tc.wantCode {
				t.Errorf("code = %q, want %q", code, tc.wantCode)
			}
			if len(git.prs) != 0 {
				t.Error("no pull request may be opened")
			}
		})
	}
}

