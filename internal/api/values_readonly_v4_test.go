// Walks 1 and 3, serious finding: on a v4 repo the add-on page's Values tab
// showed an empty editor ("1 lines, 0 chars") for a 421-line file, and the
// cluster page's Config tab only showed a red refusal. Both now answer with
// the real file, read-only, and name the file so the screen can say where to
// change it.

const walkGlobalValues = "# Generated by Sharko\nreplicaCount: 1\nimage:\n  tag: v2.2.21\n"

func getValuesJSON(t *testing.T, router http.Handler, path string) map[string]any {
	t.Helper()
	req := httptest.NewRequest(http.MethodGet, path, nil)
	w := httptest.NewRecorder()
	router.ServeHTTP(w, req)
	if w.Code != http.StatusOK {
		t.Fatalf("GET %s = %d, want 200 (body: %s)", path, w.Code, w.Body.String())
	}
	var body map[string]any
	if err := json.Unmarshal(w.Body.Bytes(), &body); err != nil {
		t.Fatalf("not JSON: %v (%s)", err, w.Body.String())
	}
	return body
}

func v4ValuesRouter(t *testing.T, files map[string][]byte) http.Handler {
	t.Helper()
	files[orchestrator.BootstrapRootAppPath] = []byte("apiVersion: argoproj.io/v1alpha1\nkind: Application\n")
	srv := serverWithGitOverride(t, newAnnotateV4Git(files))
	return NewRouter(srv, nil)
}

func TestGlobalValues_V4ShowsTheRealFileReadOnly(t *testing.T) {
	router := v4ValuesRouter(t, map[string][]byte{
		"values/global/reloader.yaml": []byte(walkGlobalValues),
	})
	body := getValuesJSON(t, router, "/api/v1/addons/reloader/values-schema")
	if body["current_values"] != walkGlobalValues {
		t.Errorf("current_values = %q, want the file exactly as it is in Git", body["current_values"])
	}
	if body["read_only"] != true {
		t.Errorf("read_only = %v, want true on a v4 repo", body["read_only"])
	}
	if body["values_file"] != "values/global/reloader.yaml" {
		t.Errorf("values_file = %v, want values/global/reloader.yaml", body["values_file"])
	}
	if body["file_exists"] != true {
		t.Errorf("file_exists = %v, want true", body["file_exists"])
	}
}

func TestGlobalValues_V4MissingFileIsSaidPlainly(t *testing.T) {
	router := v4ValuesRouter(t, map[string][]byte{})
	body := getValuesJSON(t, router, "/api/v1/addons/reloader/values-schema")
	if body["file_exists"] == true || body["current_values"] != "" {
		t.Errorf("a file that is not in Git must come back empty and not-existing, got %v", body)
	}
	if body["values_file"] != "values/global/reloader.yaml" {
		t.Errorf("values_file = %v", body["values_file"])
	}
}

func TestClusterValues_V4ShowsTheRealFileCommentsIncluded(t *testing.T) {
	// A file that holds only comments is shown as it is (walk 1 saw
	// "Unable to parse YAML" for exactly this file).
	const commentsOnly = "# Helm values for reloader on spoke-1 only. These override values/global/reloader.yaml.\n# An empty file means no cluster-specific overrides.\n"
	router := v4ValuesRouter(t, map[string][]byte{
		"values/clusters/spoke-1/reloader.yaml": []byte(commentsOnly),
	})
	body := getValuesJSON(t, router, "/api/v1/clusters/spoke-1/addons/reloader/values")
	if body["current_overrides"] != commentsOnly {
		t.Errorf("current_overrides = %q, want the comments-only file as it is", body["current_overrides"])
	}
	if body["read_only"] != true || body["values_file"] != "values/clusters/spoke-1/reloader.yaml" {
		t.Errorf("read_only/values_file = %v / %v", body["read_only"], body["values_file"])
	}
	if body["wrapped_under_addon_name"] == true {
		t.Error("a comments-only file was reported as wrapped")
	}
}

// Walk 3, serious finding: a per-cluster file written as `podinfo:` then the
// settings underneath is accepted by Git and ArgoCD and ignored by Helm, and
// Sharko said nothing. Now the cluster page learns it from this answer.
func TestClusterValues_V4SaysWhenTheFileIsWrappedUnderTheAddonName(t *testing.T) {
	router := v4ValuesRouter(t, map[string][]byte{
		"values/clusters/spoke-1/podinfo.yaml": []byte("podinfo:\n  replicaCount: 2\n"),
		"values/clusters/spoke-1/other.yaml":   []byte("replicaCount: 2\n"),
	})
	wrapped := getValuesJSON(t, router, "/api/v1/clusters/spoke-1/addons/podinfo/values")
	if wrapped["wrapped_under_addon_name"] != true {
		t.Errorf("a file wrapped under the add-on name was not reported: %v", wrapped)
	}
	plain := getValuesJSON(t, router, "/api/v1/clusters/spoke-1/addons/other/values")
	if plain["wrapped_under_addon_name"] == true {
		t.Errorf("a normal file was reported as wrapped: %v", plain)
	}
}
