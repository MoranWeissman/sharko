package orchestrator

import "testing"

const managedHeader = "# Generated by Sharko from x@1.0.0 on 2026-11-26\n# sharko: managed=true\n"

func TestClusterValuesWrapped(t *testing.T) {
	// The real shape of the reloader chart: it has a top block named reloader.
	reloaderGlobal := managedHeader + "global:\n  imageRegistry: \"\"\nimage:\n  tag: v1.4.25\nreloader:\n  autoReloadAll: false\n  deployment:\n    replicas: 1\n"
	// podinfo has no top block named podinfo.
	podinfoGlobal := managedHeader + "replicaCount: 1\nimage:\n  tag: 6.7.1\n"

	cases := []struct {
		name    string
		addon   string
		cluster string
		global  string
		want    bool
	}{
		{
			name:  "a correct reloader override is NOT wrapped (review must-fix)",
			addon: "reloader", cluster: "reloader:\n  deployment:\n    replicas: 2\n", global: reloaderGlobal, want: false,
		},
		{
			name:  "podinfo settings under podinfo: are wrapped",
			addon: "podinfo", cluster: "podinfo:\n  replicaCount: 2\n", global: podinfoGlobal, want: true,
		},
		{
			name:  "wrapped with a setting the chart defaults do not list, Sharko-written global file",
			addon: "podinfo", cluster: "podinfo:\n  somethingNew: 2\n", global: podinfoGlobal, want: true,
		},
		{
			name:  "an unwrapped file is never wrapped",
			addon: "podinfo", cluster: "replicaCount: 2\n", global: podinfoGlobal, want: false,
		},
		{
			name:  "a second top setting means it is not a wrap",
			addon: "podinfo", cluster: "podinfo:\n  replicaCount: 2\nimage:\n  tag: x\n", global: podinfoGlobal, want: false,
		},
		{
			name:  "no global file: Sharko cannot tell, so it says nothing",
			addon: "reloader", cluster: "reloader:\n  deployment:\n    replicas: 2\n", global: "", want: false,
		},
		{
			name:  "comments-only global file: Sharko cannot tell",
			addon: "reloader", cluster: "reloader:\n  deployment:\n    replicas: 2\n", global: managedHeader + "# nothing set\n", want: false,
		},
		{
			name:  "hand-written global file with few settings, correct reloader override: not wrapped",
			addon: "reloader", cluster: "reloader:\n  deployment:\n    replicas: 2\n", global: "image:\n  tag: v1\n", want: false,
		},
		{
			name:  "hand-written global file, and the block holds one of its top settings: wrapped",
			addon: "podinfo", cluster: "podinfo:\n  replicaCount: 2\n", global: "replicaCount: 1\n", want: true,
		},
		{
			name:  "comments around the block do not change the answer",
			addon: "reloader", cluster: "# my overrides\nreloader:\n  # more pods\n  deployment:\n    replicas: 2\n", global: reloaderGlobal, want: false,
		},
		{
			name:  "empty file",
			addon: "podinfo", cluster: "", global: podinfoGlobal, want: false,
		},
	}
	for _, c := range cases {
		t.Run(c.name, func(t *testing.T) {
			if got := ClusterValuesWrapped([]byte(c.cluster), []byte(c.global), c.addon); got != c.want {
				t.Errorf("ClusterValuesWrapped = %v, want %v", got, c.want)
			}
		})
	}
}
