import { describe, it, expect } from 'vitest'
import { render, screen } from '@testing-library/react'
import { ReadOnlyValues } from '@/components/ReadOnlyValues'

const BANNED = [
  'ships next wave',
  'next wave',
  "doesn't support the v4 layout yet",
  'Submit changes',
  'Submit',
  'Unable to parse YAML',
]

describe('ReadOnlyValues', () => {
  it('shows the real file, the one plain sentence with the path, and no Submit button', () => {
    const file = '# Generated by Sharko\nreplicaCount: 1\nimage:\n  tag: v2.2.21\n'
    const { container } = render(
      <ReadOnlyValues
        title="Global Values — reloader"
        path="values/global/reloader.yaml"
        exists
        content={file}
      />,
    )
    expect(
      screen.getByText(
        'Editing values here is not in this version. To change them, edit the file in your Git repo: values/global/reloader.yaml',
      ),
    ).toBeInTheDocument()
    expect(screen.getByTestId('read-only-values-content').textContent).toBe(file)
    expect(screen.queryByRole('button')).toBeNull()
    for (const b of BANNED) expect(container.textContent).not.toContain(b)
  })

  it('shows a comments-only file as it is, without a parse error', () => {
    const file = '# Helm values for reloader on spoke-1 only.\n# An empty file means no cluster-specific overrides.\n'
    const { container } = render(
      <ReadOnlyValues
        title="reloader overrides on spoke-1"
        path="values/clusters/spoke-1/reloader.yaml"
        exists
        content={file}
      />,
    )
    expect(screen.getByTestId('read-only-values-content').textContent).toBe(file)
    for (const b of BANNED) expect(container.textContent).not.toContain(b)
  })

  it('says plainly that the file is not in the repo yet', () => {
    render(
      <ReadOnlyValues
        title="t"
        path="values/global/reloader.yaml"
        exists={false}
        content=""
      />,
    )
    expect(
      screen.getByText(
        'There is no file at values/global/reloader.yaml in your Git repo yet. Create it there to set values.',
      ),
    ).toBeInTheDocument()
    expect(screen.queryByTestId('read-only-values-content')).toBeNull()
  })

  it('warns, in plain words, when the file is wrapped under the add-on name', () => {
    render(
      <ReadOnlyValues
        title="t"
        path="values/clusters/spoke-1/podinfo.yaml"
        exists
        content={'podinfo:\n  replicaCount: 2\n'}
        wrappedUnderAddon="podinfo"
      />,
    )
    expect(screen.getByRole('alert').textContent).toBe(
      'None of the settings in this file take effect. They are all inside a block named "podinfo:". Move them out of that block so they start at the left edge of the file.',
    )
  })

  it('does not show the wrapped warning for a normal file', () => {
    render(
      <ReadOnlyValues title="t" path="p.yaml" exists content={'replicaCount: 2\n'} />,
    )
    expect(screen.queryByRole('alert')).toBeNull()
  })
})
