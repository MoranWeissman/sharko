import { describe, it, expect, vi, beforeEach } from 'vitest'
import { render, screen, waitFor } from '@testing-library/react'
import { MemoryRouter, Route, Routes } from 'react-router-dom'
import { AddonDetail } from '@/views/AddonDetail'
import { AuthContext } from '@/hooks/useAuth'

/*
 * Walks 1 and 3, serious finding: on a repo in the new layout the add-on
 * page's Values tab showed an empty editor ("1 lines · 0 chars"), a yellow
 * "Couldn't load recent PRs" line and a Submit button that could only fail.
 * It now shows the real file read-only with one plain sentence and the path.
 *
 * Walk 2, serious finding: "Clusters enabled" read "2 / 2" with three
 * managed clusters. The card prints what the API sends, so the second number
 * must be the total the API sends.
 */

const GLOBAL_FILE = '# Generated by Sharko\nreplicaCount: 1\nimage:\n  tag: v2.2.21\n'
const recentPRsMock = vi.fn()

vi.mock('@/services/api', () => ({
  getAddonPRs: vi.fn().mockResolvedValue({ prs: [] }),
  upgradeAddon: vi.fn().mockResolvedValue({ pr_url: '' }),
  removeAddon: vi.fn().mockResolvedValue({}),
  configureAddon: vi.fn(),
  api: {
    getConnections: vi.fn().mockResolvedValue({ connections: [], active_connection: '' }),
    getAddonValues: vi.fn().mockRejectedValue(new Error('not found')),
    getMe: vi.fn().mockResolvedValue({ username: 'tester', role: 'admin', has_github_token: true }),
    getAddonValuesSchema: vi.fn().mockResolvedValue({
      addon_name: 'reloader',
      current_values: '# Generated by Sharko\nreplicaCount: 1\nimage:\n  tag: v2.2.21\n',
      schema: null,
      read_only: true,
      values_file: 'values/global/reloader.yaml',
      file_exists: true,
    }),
    getAddonValuesRecentPRs: (...a: unknown[]) => recentPRsMock(...a),
    getAIConfig: vi.fn().mockResolvedValue({ current_provider: 'none', available_providers: [], annotate_on_seed: false }),
    getUpgradeRecommendations: vi.fn().mockResolvedValue({ current_version: '2.2.21' }),
    getUpgradeVersions: vi.fn().mockResolvedValue({ versions: [] }),
    getAddonDetail: vi.fn().mockResolvedValue({
      addon: {
        addon_name: 'reloader',
        chart: 'reloader',
        repo_url: 'https://stakater.github.io/stakater-charts',
        namespace: 'reloader',
        version: '2.2.21',
        selfHeal: true,
        syncOptions: [],
        extraHelmValues: {},
        total_clusters: 3,
        enabled_clusters: 2,
        healthy_applications: 2,
        degraded_applications: 0,
        missing_applications: 0,
        applications: [],
      },
    }),
  },
}))

const adminCtx = {
  token: 't',
  username: 'tester',
  role: 'admin',
  login: vi.fn(),
  logout: vi.fn(),
  isAuthenticated: true,
  isAdmin: true,
  loading: false,
  error: null,
}

function renderSection(section: string) {
  return render(
    <AuthContext.Provider value={adminCtx}>
      <MemoryRouter initialEntries={[`/addons/reloader?section=${section}`]}>
        <Routes>
          <Route path="/addons/:name" element={<AddonDetail />} />
        </Routes>
      </MemoryRouter>
    </AuthContext.Provider>,
  )
}

describe('AddonDetail — Values tab on a v4 repo', () => {
  beforeEach(() => {
    vi.clearAllMocks()
  })

  it('shows the real file read-only, the plain sentence with the path, and no Submit button', async () => {
    const { container } = renderSection('values')
    await waitFor(() => expect(screen.getByTestId('read-only-values')).toBeInTheDocument())
    expect(screen.getByTestId('read-only-values-content').textContent).toBe(GLOBAL_FILE)
    expect(container.textContent).toContain(
      'Editing values here is not in this version. To change them, edit the file in your Git repo: values/global/reloader.yaml',
    )
    expect(screen.queryByRole('button', { name: /submit/i })).toBeNull()
    for (const banned of ['ships next wave', "doesn't support the v4 layout yet", "Couldn't load recent PRs", '1 lines']) {
      expect(container.textContent).not.toContain(banned)
    }
    expect(recentPRsMock).not.toHaveBeenCalled()
  })
})

describe('AddonDetail — Clusters enabled card', () => {
  it('prints turned on out of all managed clusters', async () => {
    const { container } = renderSection('overview')
    await waitFor(() => expect(container.textContent).toContain('Clusters enabled'))
    expect(container.textContent).toContain('2 / 3')
    expect(container.textContent).not.toContain('2 / 2')
  })
})
